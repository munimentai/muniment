import { afterEach, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/svelte'
import '@testing-library/jest-dom/vitest'
import ProjectCatalog from './ProjectCatalog.svelte'
afterEach(cleanup)

it('searches projects and opens only their assigned threads', async () => {
  const onthread = vi.fn(), onnewthread = vi.fn()
  render(ProjectCatalog, { projects: [['a', 'Research'], ['b', 'Writing']], threads: [{threadId:'one',title:'Sources'}, {threadId:'two',title:'Draft'}], assignments: {one:'a',two:'b'}, onthread, onnewthread })
  await fireEvent.input(screen.getByRole('searchbox'), {target:{value:'research'}})
  expect(screen.queryByRole('button', {name:/Writing/})).toBeNull()
  await fireEvent.click(screen.getByRole('button', {name:'Research 1 thread'}))
  expect(screen.queryByRole('button', {name:'Draft'})).toBeNull()
  await fireEvent.click(screen.getByRole('button', {name:'Sources'}))
  expect(onthread).toHaveBeenCalledWith('one')
  await fireEvent.click(screen.getByRole('button', {name:'New thread'}))
  expect(onnewthread).toHaveBeenCalledWith('a')
  await fireEvent.click(screen.getByRole('button', {name:'Back to projects'}))
  expect(screen.getByRole('searchbox').value).toBe('research')
})

it('creates a named project and keeps the form open when creation fails', async () => {
  const oncreate = vi.fn().mockResolvedValueOnce(false).mockResolvedValueOnce(true)
  render(ProjectCatalog, {oncreate})
  await fireEvent.click(screen.getByRole('button', {name:'New project'}))
  await fireEvent.input(screen.getByRole('textbox', {name:'Project name'}), {target:{value:' Research '}})
  await fireEvent.click(screen.getByRole('button', {name:'Create',exact:true}))
  await waitFor(() => expect(oncreate).toHaveBeenCalledWith('Research'))
  expect(screen.getByRole('textbox', {name:'Project name'})).not.toBeNull()
  await fireEvent.click(screen.getByRole('button', {name:'Create',exact:true}))
  await waitFor(() => expect(screen.queryByRole('textbox', {name:'Project name'})).toBeNull())
})

it('offers rename, new thread, and open folder from the project card menu', async () => {
  const onrename = vi.fn(), onnewthread = vi.fn(), onopen = vi.fn()
  render(ProjectCatalog, {projects:[['a','Research']], onrename, onnewthread, onopen})
  await fireEvent.click(screen.getByRole('button', {name:'Actions for Research'}))
  expect(screen.queryByRole('menuitem', {name:'Delete'})).toBeNull()
  await fireEvent.click(screen.getByRole('menuitem', {name:'Rename'}))
  await fireEvent.input(screen.getByRole('textbox', {name:'Name'}), {target:{value:'Product launch'}})
  await fireEvent.click(screen.getByRole('button', {name:'Save'}))
  await waitFor(() => expect(onrename).toHaveBeenCalledWith('a','Product launch'))
  await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
  await fireEvent.click(screen.getByRole('button', {name:'Actions for Research'}))
  await fireEvent.click(screen.getByRole('menuitem', {name:'Open folder'}))
  await waitFor(() => expect(onopen).toHaveBeenCalledWith('a'))
  await waitFor(() => expect(screen.queryByRole('menu')).toBeNull())
  await fireEvent.click(screen.getByRole('button', {name:'Actions for Research'}))
  await fireEvent.click(screen.getByRole('menuitem', {name:'New thread'}))
  await waitFor(() => expect(onnewthread).toHaveBeenCalledWith('a'))
})

it('lists other members\' projects after own ones with their owner, and opens one like its sidebar row', async () => {
  const onnewthread = vi.fn(), onthread = vi.fn()
  const studio = { name: 'Studio', kind: 'desktop', online: false }
  render(ProjectCatalog, { projects: [['a', 'Research']], remote: [['r', 'Launch plan', studio]], threads: [{threadId:'one',title:'Sources'}, {threadId:'two',title:'Checklist'}], assignments: {one:'a',two:'r'}, onnewthread, onthread })
  const cards = screen.getAllByRole('button', { name: /thread/ })
  expect(cards.map((card) => card.getAttribute('aria-label'))).toEqual(['Research 1 thread', 'Launch plan 1 thread, files on Studio, offline'])
  expect(cards[1]).toHaveTextContent('files on Studio')
  expect(screen.queryByRole('button', { name: 'Actions for Launch plan' })).toBeNull()
  await fireEvent.input(screen.getByRole('searchbox'), {target:{value:'launch'}})
  expect(screen.queryByRole('button', { name: /^Research/ })).toBeNull()
  await fireEvent.click(screen.getByRole('button', { name: /^Launch plan/ }))
  expect(screen.getByRole('heading', { name: 'Launch plan', level: 2 })).toBeInTheDocument()
  expect(screen.getByText('files on Studio')).toBeInTheDocument()
  await fireEvent.click(screen.getByRole('button', { name: 'Checklist' }))
  expect(onthread).toHaveBeenCalledWith('two')
  await fireEvent.click(screen.getByRole('button', { name: 'New thread' }))
  expect(onnewthread).toHaveBeenCalledWith('r')
})
